#!/usr/bin/env bash
# LR-147 (docs gap research row 4, 27 Nov): a lane that dies on an API error is never silent.
#   lane-death.sh            StopFailure hook (.claude/settings.json). Docs, code.claude.com/docs/en/hooks, read 27 Nov
#                            2026: StopFailure fires "when the turn ends due to an API error"; input adds `error`
#                            (rate_limit, authentication_failed, oauth_org_not_allowed, account_on_hold, billing_error,
#                            invalid_request, model_not_found, server_error, max_output_tokens, cloud_credential_error,
#                            unknown), `error_details`, `last_assistant_message`; "Claude Code ignores the hook's output
#                            and exit code". Writes one line to LANE_DEATH_LOG (default ~/.claude/xr-lane-deaths.tsv) and,
#                            when the session's branch has an open PR here, one PR comment "Lane stopped (StopFailure): ..."
#                            (a cloud lane's container is not the Mac: the comment is what the Lead's check can see). Reads
#                            and one comment only; nothing priced; never fails the session.
#   lane-death.sh read [M]   lead-watch: one "ACT   lane death: ..." line per death in the last M minutes (default 30):
#                            the local log, and PRs whose comments carry the marker (GitHub search, read only). A search
#                            that fails is one ACT too (never a silent "no deaths").
# Env: LANE_DEATH_LOG, REPO (owner/name; default from origin), NOW (epoch, tests). Test: check-lane-death.sh.
set -u
LOG="${LANE_DEATH_LOG:-$HOME/.claude/xr-lane-deaths.tsv}"; MARK="Lane stopped (StopFailure):"
now=${NOW:-$(date +%s)}; iso() { date -u -d "@$1" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || date -u -r "$1" +%Y-%m-%dT%H:%M:%SZ; }
repo() { [ -n "${REPO:-}" ] && { echo "$REPO"; return; }; git -C "${1:-.}" remote get-url origin 2>/dev/null | sed -E 's#^.*github\.com[:/]##; s#\.git$##'; }
if [ "${1:-}" = read ]; then
  m=${2:-30}; since=$((now - m * 60)); n=0
  if [ -s "$LOG" ]; then
    while IFS=$'\t' read -r t sid err br det; do
      [[ "$t" =~ ^[0-9]+$ ]] && [ "$t" -gt "$since" ] || continue
      echo "ACT   lane death: session $sid stopped on $err at $(iso "$t") (branch ${br:--}; $det): read it, then restart it from its PR's hand-over or tell the founder (billing, sign-in)"; n=$((n + 1))
    done < "$LOG"
  fi
  r=$(repo "$(dirname "$0")")
  hits=$(gh api -X GET search/issues -f q="repo:$r is:pr \"$MARK\" updated:>=$(iso "$since")" --jq '.items[] | "\(.number)\t\(.title)"' 2>/dev/null) \
    || { echo "ACT   lane death: the GitHub search for \"$MARK\" failed; deaths of cloud lanes are unknown this check"; exit 0; }
  while IFS=$'\t' read -r num title; do [ -n "$num" ] || continue
    echo "ACT   lane death: PR #$num ($title) has a \"$MARK\" comment in the last $m min: read it and restart the lane"; n=$((n + 1))
  done <<< "$hits"
  echo "lane deaths: $n in the last $m min"; exit 0
fi
in=$(cat 2>/dev/null)
f() { printf '%s' "$in" | jq -r "$1 // empty" 2>/dev/null | tr -d '\t\r' | tr '\n' ' ' | tr -d '`' | sed 's/[[:space:]]*$//' | cut -c1-${2:-160}; }
err=$(f .error 40 | tr -cd 'a-z_'); sid=$(f .session_id 80 | tr -cd 'A-Za-z0-9_-'); det=$(f .error_details); cwd=$(f .cwd 400)
[ -n "$err" ] || err=unknown
br=$(git -C "${cwd:-.}" branch --show-current 2>/dev/null)
mkdir -p "$(dirname "$LOG")" 2>/dev/null && printf '%s\t%s\t%s\t%s\t%s\n' "$now" "${sid:--}" "$err" "${br:--}" "${det:--}" >> "$LOG"
[ -n "$br" ] && [ "$br" != main ] || exit 0
r=$(repo "${cwd:-.}"); [ -n "$r" ] || exit 0
pr=$(timeout 10 gh api "repos/$r/pulls?state=open&head=${r%%/*}:$br" --jq '.[0].number // empty' 2>/dev/null)
[ -n "$pr" ] || exit 0
body="**$MARK** \`$err\` at $(iso "$now"), session \`${sid:--}\`, branch \`$br\`${det:+: $det}. The lane's turn ended on an API error; the Lead's next check reports it (LR-147).

---
_Generated by [Claude Code](https://claude.ai/code)_"
timeout 10 gh api -X POST "repos/$r/issues/$pr/comments" -f body="$body" >/dev/null 2>&1 || true
exit 0
