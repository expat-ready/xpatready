#!/usr/bin/env python3
# Requirement traceability as data (TR-1, P-595): each Release 1 backlog row carries `Source:` (the team's fine
# requirement ids with a short content hash, P-decisions, official sources); this script reads them and
#   --brief <row>        prints only that row's requirement text (the slice a brief carries)
#   --refresh <old> <new> compares two requirement snapshots by id and hash: added, removed, renumbered, changed ids
#                         and the rows each one hits
#   --gaps               Release 1 rows with no Source, checklist rows not shaped, team ids no row covers (by module),
#                         and conflicts with founder decisions (to the founder, AGENTS rule 2)
#   --render [--check]   writes the generated trace block into MVP-CHECKLIST.md section A between markers
#   --ci <ref|file>      fails when a shaped Release 1 row added since <ref> has no Source (records-only CI step)
#   --hash <id>...       prints each id's current hash (what a row owner pastes into `Source:`)
# Sources are read from BACKLOG.md rows (`Source: AG-2-4#1a2b3c4d, P-566; deviates SA-4-4 by P-566`) and from
# trace/sources-seed.tsv (row, ref, hash). Requirement snapshots: ../domain/requirements-YYYY-MM-DD/ (the name-free,
# read-only copies tools/sync-requirements.sh writes). Standard library only (P-502). Prints requirement text to the
# terminal only; nothing it writes into git holds requirement text (P-504): the rendered block has ids and hashes.
# Brief line (row part 4): see BRIEF_LINE below.
import argparse, difflib, hashlib, os, re, signal, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PRODUCT = os.path.dirname(HERE)
P1 = os.path.dirname(PRODUCT)
DOMAIN = os.path.join(P1, "domain")
BRIEF_LINE = "Cite your row's Source ids; read only the text `trace-requirements.py --brief <row>` prints."
BEGIN = "<!-- trace-requirements:begin (generated by tools/trace-requirements.py --render; never hand-edited) -->"
END = "<!-- trace-requirements:end -->"
R1_PREFIXES = ("PF", "FO", "CS", "AUD", "MON")          # Release 1 modules (P-575, P-584); plus rows named in the checklist
ID = r"(?:AG|SA)-\d+[A-Z]?-\d+[a-z]?"
ID_RE = re.compile(r"(?<![\w-])(%s)(?![\w-])" % ID)
HOME_RE = re.compile(r"^(AG|SA)-0*(\d+)([A-Z]?)-")      # module file name -> its id prefix (AG-02-... -> AG-2)
ROW_ID = r"[A-Z][A-Za-z0-9]*-[A-Za-z0-9.]+"
P_RE = re.compile(r"^P-\d+$")
HASH_LEN = 8
DATE_RE = re.compile(r"\b(20\d\d-\d\d-\d\d|\d{1,2} [A-Z][a-z]{2,8} 20\d\d)\b")


# ---------------------------------------------------------------- requirement snapshots
def norm(text):
    return re.sub(r"\s+", " ", text).strip()


def content_hash(text):
    """Short hash of a requirement's text: whitespace collapsed, its own id(s) in the definition line replaced by <ID>,
    so a renumbered requirement with the same words keeps its hash."""
    return hashlib.sha256(norm(text).encode("utf-8")).hexdigest()[:HASH_LEN]


def module_of(rid):
    return rid.rsplit("-", 1)[0]


def snapshot_dir(arg):
    if os.path.isdir(arg):
        return arg
    d = os.path.join(DOMAIN, arg if arg.startswith("requirements-") else "requirements-" + arg)
    if os.path.isdir(d):
        return d
    raise SystemExit(f"no requirement snapshot {arg} (looked in {DOMAIN})")


def newest_snapshot():
    snaps = sorted(d for d in os.listdir(DOMAIN) if re.fullmatch(r"requirements-\d{4}-\d\d-\d\d", d))
    if not snaps:
        raise SystemExit(f"no requirements-* folder in {DOMAIN}")
    return os.path.join(DOMAIN, snaps[-1])


def home_files(root):
    """{module prefix: path} for each module's own file: the versioned one (AG-02-prospect-..._v2.6_....md -> AG-2);
    decision logs, change notes and hand-overs beside it (no _v<version> in the name) are not homes."""
    cands = {}
    for dp, _, fs in os.walk(root):
        for f in fs:
            m = HOME_RE.match(f)
            v = re.search(r"_v(\d+)\.(\d+)", f)
            if m and v and f.endswith(".md"):
                key = f"{m.group(1)}-{int(m.group(2))}{m.group(3)}"
                cands.setdefault(key, []).append(((int(v.group(1)), int(v.group(2))), os.path.join(dp, f)))
    return {k: max(v)[1] for k, v in cands.items()}


LEAD_IDS = re.compile(r"^(\s*(?:#{1,6}|[-*]|\d+\.|\|)\s*[*`~]*)((?:%s)(?:[*`]*\s*(?:,|/|and|&|–|to)\s*[*`]*(?:%s))*)" % (ID, ID))
RANGE_RE = re.compile(r"(%s)[*`]*\s*(?:–|to)\s*[*`]*(%s)" % (ID, ID))


def lead_ids(group):
    """Ids a definition line starts with; a range 'AG-6-50 – AG-6-56' gives every number in it."""
    ids = []
    for a, b in RANGE_RE.findall(group):
        ma, mb = re.fullmatch(r"(.*-)(\d+)", a), re.fullmatch(r"(.*-)(\d+)", b)
        if ma and mb and ma.group(1) == mb.group(1) and 0 < int(mb.group(2)) - int(ma.group(2)) <= 50:
            ids += [f"{ma.group(1)}{k}" for k in range(int(ma.group(2)), int(mb.group(2)) + 1)]
    for x in ID_RE.findall(group):
        if x not in ids:
            ids.append(x)
    return ids
WITHDRAWN = re.compile(r"^\s*(?:#{1,6}|[-*]|\d+\.|\|)\s*~~|\bWithdrawn\b")
KIND_RANK = {"heading": 0, "bullet": 1, "table": 2}


def parse_module(text, prefix):
    """{id: (kind, line_no, block)} for ids of this module defined in its home file. A definition is a heading
    (block to the next heading of the same or higher level), a list item (the item and its indented lines) or a table
    row (that row), whose first thing is the id (or a list of ids sharing one block). Heading beats list item beats
    table row; the first of a kind wins."""
    lines = text.split("\n")
    found = {}
    for i, line in enumerate(lines):
        if line.startswith(">"):
            continue
        m = LEAD_IDS.match(line)
        if not m:
            continue
        ids = [x for x in lead_ids(m.group(2)) if module_of(x) == prefix]
        if not ids:
            continue
        lead = m.group(1).strip()
        if lead.startswith("#"):
            kind, level = "heading", len(lead) - len(lead.lstrip("#"))
            j = i + 1
            while j < len(lines):
                h = re.match(r"^(#{1,6}) ", lines[j])
                if h and len(h.group(1)) <= level:
                    break
                j += 1
        elif lead.startswith("|"):
            kind, j = "table", i + 1
        else:
            kind = "bullet"
            ind = len(line) - len(line.lstrip())
            j = i + 1
            while j < len(lines):
                l = lines[j]
                if not l.strip():
                    k = j + 1
                    while k < len(lines) and not lines[k].strip():
                        k += 1
                    if k < len(lines) and len(lines[k]) - len(lines[k].lstrip()) > ind:
                        j = k
                        continue
                    break
                if len(l) - len(l.lstrip()) <= ind or l.startswith("#"):
                    break
                j += 1
        block = "\n".join(lines[i:j]).rstrip()
        first = line[:m.start(2)] + "<ID>" + line[m.end(2):]
        hashed = "\n".join([first] + lines[i + 1:j]).rstrip()
        for rid in ids:
            old = found.get(rid)
            if old is None or KIND_RANK[kind] < KIND_RANK[old[0]]:
                found[rid] = (kind, i + 1, block, content_hash(hashed), bool(WITHDRAWN.search(line)))
    return found


class Snapshot:
    def __init__(self, root):
        self.root = root
        self.name = os.path.basename(os.path.normpath(root))
        self.homes = home_files(root)
        self.reqs = {}        # id -> dict(module, file, line, kind, text, hash)
        self.module_size = {}
        for prefix, path in sorted(self.homes.items()):
            with open(path, encoding="utf-8") as fh:
                text = fh.read()
            self.module_size[prefix] = len(text.encode("utf-8"))
            for rid, (kind, ln, block, h, wd) in parse_module(text, prefix).items():
                self.reqs[rid] = {"module": prefix, "file": os.path.relpath(path, root), "line": ln, "kind": kind,
                                  "text": block, "hash": h, "withdrawn": wd}

    def by_module(self):
        out = {}
        for rid in self.reqs:
            out.setdefault(module_of(rid), []).append(rid)
        return {k: sorted(v, key=id_key) for k, v in out.items()}


def id_key(rid):
    parts = re.findall(r"\d+|[A-Za-z]+", rid)
    return [(0, int(p), "") if p.isdigit() else (1, 0, p) for p in parts]


# ---------------------------------------------------------------- refresh: compare two snapshots
def compare(old, new, fuzzy=0.9):
    o, n = old.reqs, new.reqs
    removed = sorted(set(o) - set(n), key=id_key)
    added = sorted(set(n) - set(o), key=id_key)
    changed = sorted((r for r in set(o) & set(n) if o[r]["hash"] != n[r]["hash"]), key=id_key)
    renumbered = []
    by_hash = {}
    for a in added:
        by_hash.setdefault(n[a]["hash"], []).append(a)
    for r in list(removed):
        cands = by_hash.get(o[r]["hash"])
        if cands:
            a = cands.pop(0)
            renumbered.append((r, a, "same text"))
    taken = {a for _, a, _ in renumbered} | {r for r, _, _ in renumbered}
    rest_added = [a for a in added if a not in taken]
    for r in [x for x in removed if x not in taken]:
        best, score = None, 0.0
        ot = norm(o[r]["text"]).replace(r, "<ID>")
        for a in rest_added:
            if module_of(a) != module_of(r):
                continue
            nt = norm(n[a]["text"]).replace(a, "<ID>")
            sm = difflib.SequenceMatcher(None, ot, nt, autojunk=False)
            if sm.real_quick_ratio() < fuzzy or sm.quick_ratio() < fuzzy:
                continue
            s = sm.ratio()
            if s >= fuzzy and s > score:
                best, score = a, s
        if best:
            renumbered.append((r, best, f"text {int(score * 100)}% alike"))
            rest_added.remove(best)
            taken |= {r, best}
    renumbered.sort(key=lambda t: id_key(t[0]))
    return {"added": [a for a in added if a not in taken], "removed": [r for r in removed if r not in taken],
            "renumbered": renumbered, "changed": changed}


# ---------------------------------------------------------------- records: BACKLOG, seed, checklist, decisions, qa
def cells(line):
    """Table cells, keeping a | inside backticks or escaped as \\| in its cell."""
    out, cur, tick, i = [], [], False, 0
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s) and s[i + 1] == "|":
            cur.append("|"); i += 2; continue
        if ch == "`":
            tick = not tick
        if ch == "|" and not tick:
            out.append("".join(cur).strip()); cur = []
        else:
            cur.append(ch)
        i += 1
    if "".join(cur).strip():
        out.append("".join(cur).strip())
    return out


SEP = re.compile(r"^\|\s*:?-{3,}")
ROW_LINE = re.compile(r"^\|\s*(%s)(\s*\([^|]*\))?\s*\|" % ROW_ID)


def parse_backlog(text):
    """{row id: {"shaped": bool, "lines": [line, ...], "first": line no}}. A row's main line is its first table line
    under a header with a "Done when" column; shaped = that cell is filled. Amendment lines ("FO-2 (rev 15.1
    amendment)") and later tables add lines (for Source) but never make a row shaped."""
    rows, hdr, prev = {}, None, None
    for n, line in enumerate(text.split("\n"), 1):
        if SEP.match(line) and prev is not None and prev.startswith("|"):
            hdr = [h.lower() for h in cells(prev)]
        m = ROW_LINE.match(line)
        prev = line
        if not m or SEP.match(line):
            continue
        rid, amend = m.group(1), m.group(2)
        r = rows.setdefault(rid, {"shaped": False, "lines": [], "first": n, "main": None})
        r["lines"].append(line)
        if amend or not hdr or r["main"] is not None:
            continue
        di = next((k for k, h in enumerate(hdr) if h.startswith("done when")), None)
        if di is None:
            continue
        c = cells(line)
        r["main"] = n
        dw = c[di] if di < len(c) else ""
        r["shaped"] = bool(dw) and not re.fullmatch(r"(as [A-Z].*|-|—|tbd|TBD)", dw)
    return rows


SOURCE_RE = re.compile(r"(?<![`\w])\**Source:\**\s*(.+?)(?=\s+·\s|\s*\||$)")


def parse_source(value):
    """'AG-2-4#1a2b3c4d, P-566; official: canada.ca/... p.3, 2026-11-01; deviates SA-4-4 by P-566' ->
    list of refs {kind: team|decision|official|deviates|unknown, ...}."""
    refs = []
    for item in re.split(r"[;,](?![^()]*\))", value.replace("`", "")):
        it = item.strip().rstrip(".")
        if not it:
            continue
        m = re.fullmatch(r"(%s)(?:#([0-9a-f]{%d}))?" % (ID, HASH_LEN), it)
        if m:
            refs.append({"kind": "team", "id": m.group(1), "hash": m.group(2)}); continue
        if P_RE.fullmatch(it):
            refs.append({"kind": "decision", "id": it}); continue
        m = re.fullmatch(r"deviates\s+(%s)\s+by\s+(P-\d+)" % ID, it)
        if m:
            refs.append({"kind": "deviates", "id": m.group(1), "decision": m.group(2)}); continue
        if it.lower().startswith("official"):
            refs.append({"kind": "official", "text": it.split(":", 1)[-1].strip(), "dated": bool(DATE_RE.search(it))})
            continue
        refs.append({"kind": "unknown", "text": it})
    return refs


def merge_official_dates(refs):
    """An official source's page and date are written with commas ('official: url p.3, 2026-11-01'): join a bare
    date or page item that follows an official item back onto it."""
    out = []
    for r in refs:
        if r["kind"] == "unknown" and out and out[-1]["kind"] == "official":
            out[-1]["text"] += ", " + r["text"]
            out[-1]["dated"] = out[-1]["dated"] or bool(DATE_RE.search(r["text"]))
            continue
        out.append(r)
    return out


def read_seed(path):
    seed = {}
    if not path or not os.path.exists(path):
        return seed
    with open(path, encoding="utf-8") as fh:
        for n, line in enumerate(fh, 1):
            if not line.strip() or line.startswith("#"):
                continue
            f = line.rstrip("\n").split("\t")
            if f[0] == "row":
                continue
            if len(f) < 2:
                raise SystemExit(f"{path}:{n}: want row<TAB>ref[<TAB>hash]")
            ref = f[1].strip() + (("#" + f[2].strip()) if len(f) > 2 and f[2].strip() else "")
            seed.setdefault(f[0].strip(), []).extend(parse_source(ref))
    return seed


def row_sources(rows, seed):
    """{row id: [refs]} from the rows' own Source lines plus the seed file."""
    out = {}
    for rid, r in rows.items():
        for line in r["lines"]:
            for m in SOURCE_RE.finditer(line):
                out.setdefault(rid, []).extend(merge_official_dates(parse_source(m.group(1))))
    for rid, refs in seed.items():
        out.setdefault(rid, []).extend(refs)
    return out


CK_ROW = re.compile(r"^\|\s*(\d+)\s*\|")


def parse_checklist(text):
    """Section A's hand tables (header '| Map |'): [{map, cap, module, rows_cell, status, row_ids}]."""
    out, inA, hdr, gen = [], False, None, False
    for line in text.split("\n"):
        if line.startswith("## "):
            inA = line.startswith("## A.")
        if line.startswith(BEGIN[:30]):
            gen = True
        if line.startswith(END):
            gen = False
            continue
        if not inA or gen:
            continue
        if line.startswith("| Map |"):
            hdr = [h.lower() for h in cells(line)]
            continue
        m = CK_ROW.match(line)
        if m and hdr:
            c = cells(line)
            col = lambda name: next((i for i, h in enumerate(hdr) if h.startswith(name)), None)
            rc = c[col("backlog")] if col("backlog") is not None and col("backlog") < len(c) else ""
            st = c[col("status")] if col("status") is not None and col("status") < len(c) else ""
            out.append({"map": int(m.group(1)), "cap": c[1] if len(c) > 1 else "", "rows_cell": rc, "status": st,
                        "row_ids": cell_row_ids(rc)})
    return out


def cell_row_ids(cell):
    ids = []
    for x in re.findall(r"(?<![\w-])((?:PF|FO|BK|AUD|AS|CS|MON)-[0-9A-Za-z]+)(?![\w-])", cell):
        if x not in ids:
            ids.append(x)
    return ids


def status_word(st):
    s = st.replace("\\*", "").replace("*", "").strip()
    for w in ("Not shaped", "Shaped", "In PR", "Merged", "qa Works"):
        if s.startswith(w):
            return w
    return s.split(" (")[0]


def parse_decisions(text):
    """{P-id: {"struck": bool, "text": line}}."""
    out = {}
    for line in text.split("\n"):
        m = re.match(r"^\|\s*(~~)?\s*(P-\d+)", line)
        if m:
            c = cells(line)
            struck = bool(m.group(1)) or (len(c) > 2 and c[2].startswith("~~"))   # superseded lines are struck through
            out.setdefault(m.group(2), {"struck": struck, "text": line})
    return out


DEVIATE_WORDS = re.compile(r"deviat|instead of|overrid|supersed|not follow", re.I)


def decision_deviations(decisions):
    """{team id: [P-id]} where a decision's own text says it deviates from (overrides, supersedes) that id."""
    out = {}
    for pid, d in decisions.items():
        for sent in re.split(r"(?<=[.;])\s", d["text"]):
            if DEVIATE_WORDS.search(sent):
                for rid in ID_RE.findall(sent):
                    out.setdefault(rid, [])
                    if pid not in out[rid]:
                        out[rid].append(pid)
    return out


def capabilities_for(caps_text, row_ids):
    """qa capability ids (C1.2 style) whose line cites one of the rows, or that are marked R1 in the M column."""
    out = []
    for line in caps_text.split("\n"):
        m = re.match(r"^\|\s*(C\d+(?:\.\d+)+[a-z]?)\s*\|", line)
        if not m:
            continue
        c = cells(line)
        hit = any(re.search(r"(?<![\w-])%s(?![\w-])" % re.escape(r), line) for r in row_ids)
        if hit and m.group(1) not in out:
            out.append(m.group(1))
    return out


def r1_rows(rows, checklist):
    named = {x for c in checklist for x in c["row_ids"]}
    return sorted((r for r in rows if r.split("-")[0] in R1_PREFIXES or r in named), key=id_key)


# ---------------------------------------------------------------- context
class Ctx:
    def __init__(self, a):
        self.a = a
        self.backlog_path = a.backlog or os.path.join(PRODUCT, "BACKLOG.md")
        self.checklist_path = a.checklist or os.path.join(PRODUCT, "MVP-CHECKLIST.md")
        self.decisions_path = a.decisions or os.path.join(PRODUCT, "DECISIONS.md")
        self.caps_path = a.capabilities or os.path.join(PRODUCT, "qa", "CAPABILITIES.md")
        self.seed_path = a.seed if a.seed is not None else os.path.join(PRODUCT, "trace", "sources-seed.tsv")
        self.snapshot_path = snapshot_dir(a.snapshot) if a.snapshot else newest_snapshot()
        self._snap = None

    def read(self, p):
        if not os.path.exists(p):
            return ""
        with open(p, encoding="utf-8") as fh:
            return fh.read()

    @property
    def snap(self):
        if self._snap is None:
            self._snap = Snapshot(self.snapshot_path)
        return self._snap

    def load(self):
        self.rows = parse_backlog(self.read(self.backlog_path))
        self.checklist = parse_checklist(self.read(self.checklist_path))
        self.decisions = parse_decisions(self.read(self.decisions_path))
        self.sources = row_sources(self.rows, read_seed(self.seed_path))
        self.r1 = r1_rows(self.rows, self.checklist)
        return self


def rows_citing(sources):
    hit = {}
    for rid, refs in sources.items():
        for ref in refs:
            if ref["kind"] in ("team", "deviates"):
                hit.setdefault(ref["id"], [])
                if rid not in hit[ref["id"]]:
                    hit[ref["id"]].append(rid)
    return hit


# ---------------------------------------------------------------- commands
def cmd_brief(ctx, row):
    ctx.load()
    refs = ctx.sources.get(row)
    if row not in ctx.rows and row not in ctx.sources:
        print(f"no BACKLOG row {row}", file=sys.stderr); return 2
    if not refs:
        print(f"{row} has no Source yet (BACKLOG Source line or trace/sources-seed.tsv)", file=sys.stderr); return 1
    snap, bad, seen = ctx.snap, 0, set()
    print(f"# Requirement text for {row} ({snap.name})\n{BRIEF_LINE}\n")
    for ref in refs:
        key = (ref["kind"], ref.get("id") or ref.get("text"))
        if key in seen:
            continue
        seen.add(key)
        if ref["kind"] in ("team", "deviates"):
            req = snap.reqs.get(ref["id"])
            if not req:
                print(f"## {ref['id']}: NOT FOUND in {snap.name}\n"); bad += 1; continue
            note = ""
            if req["withdrawn"]:
                note += " · WITHDRAWN in this snapshot: ask the row owner"; bad += 1
            if ref["kind"] == "deviates":
                note += f" · deviated from by {ref['decision']} (do not build it as written)"
            elif not ref.get("hash"):
                note += f" · Source has no hash (now {req['hash']})"
            elif ref["hash"] != req["hash"]:
                note += f" · CHANGED since mapped ({ref['hash']} -> {req['hash']}): ask the row owner"; bad += 1
            print(f"## {ref['id']} · {req['file']}:{req['line']} · #{req['hash']}{note}\n{req['text']}\n")
        elif ref["kind"] == "decision":
            d = ctx.decisions.get(ref["id"])
            print(f"## {ref['id']}{' (struck through)' if d and d['struck'] else ''}\n{d['text'] if d else 'NOT FOUND in DECISIONS.md'}\n")
        elif ref["kind"] == "official":
            print(f"## Official source\n{ref['text']}\n")
        else:
            print(f"## Unread Source item: {ref['text']}\n")
    return 1 if bad else 0


def cmd_hash(ctx, ids):
    rc = 0
    for rid in ids:
        r = ctx.snap.reqs.get(rid)
        if r:
            print(f"{rid}#{r['hash']}\t{r['file']}:{r['line']}")
        else:
            print(f"{rid}\tNOT FOUND in {ctx.snap.name}"); rc = 1
    return rc


def cmd_refresh(ctx, old_arg, new_arg):
    ctx.load()
    old, new = Snapshot(snapshot_dir(old_arg)), Snapshot(snapshot_dir(new_arg))
    d = compare(old, new)
    hit = rows_citing(ctx.sources)
    hits = lambda rid: (" -> rows " + ", ".join(hit[rid])) if rid in hit else ""
    print(f"# Requirement refresh {old.name} -> {new.name}")
    print(f"ids: {len(old.reqs)} -> {len(new.reqs)} · added {len(d['added'])} · removed {len(d['removed'])} · "
          f"renumbered {len(d['renumbered'])} · changed {len(d['changed'])}")
    rows_hit = sorted({r for x in d["removed"] + d["changed"] + [o for o, _, _ in d["renumbered"]] for r in hit.get(x, [])}, key=id_key)
    print(f"rows hit: {len(rows_hit)}{(' (' + ', '.join(rows_hit) + ')') if rows_hit else ''}\n")
    print(f"## Renumbered ({len(d['renumbered'])})")
    for o, n, why in d["renumbered"]:
        print(f"{o} -> {n} ({why}){hits(o)}")
    print(f"\n## Changed: same id, new text ({len(d['changed'])})")
    for r in d["changed"]:
        wd = " (now withdrawn)" if new.reqs[r]["withdrawn"] and not old.reqs[r]["withdrawn"] else ""
        print(f"{r} #{old.reqs[r]['hash']} -> #{new.reqs[r]['hash']}{wd}{hits(r)}")
    print(f"\n## Removed ({len(d['removed'])})")
    for r in d["removed"]:
        print(f"{r}{hits(r)}")
    print(f"\n## Added ({len(d['added'])})")
    for m, ids in group_by_module(d["added"]).items():
        print(f"{m} ({len(ids)}): {', '.join(ids)}")
    return 0


def group_by_module(ids):
    out = {}
    for r in sorted(ids, key=id_key):
        out.setdefault(module_of(r), []).append(r)
    return dict(sorted(out.items(), key=lambda kv: id_key(kv[0])))


def gaps(ctx):
    ctx.load()
    snap = ctx.snap
    no_source = [r for r in ctx.r1 if ctx.rows.get(r, {}).get("shaped") and not ctx.sources.get(r)]
    unshaped = [c for c in ctx.checklist if status_word(c["status"]) == "Not shaped"]
    cited = set(rows_citing(ctx.sources))
    blocks = {(snap.reqs[r]["file"], snap.reqs[r]["line"]) for r in cited if r in snap.reqs}
    covered = cited | {r for r, q in snap.reqs.items() if (q["file"], q["line"]) in blocks}   # ids sharing a cited block
    uncovered = {m: [r for r in ids if r not in covered and not snap.reqs[r]["withdrawn"]] for m, ids in snap.by_module().items()}
    stale, missing, struck, declared, unknown, undated, conflicts = [], [], [], [], [], [], []
    devs = decision_deviations(ctx.decisions)
    for rid in sorted(ctx.sources, key=id_key):
        cited_p = {x["id"] for x in ctx.sources[rid] if x["kind"] == "decision"}
        for ref in ctx.sources[rid]:
            k = ref["kind"]
            if k in ("team", "deviates"):
                req = snap.reqs.get(ref["id"])
                if not req:
                    missing.append((rid, ref["id"]))
                elif k == "team" and ref.get("hash") and ref["hash"] != req["hash"]:
                    stale.append((rid, ref["id"], ref["hash"], req["hash"]))
                elif k == "team" and not ref.get("hash"):
                    stale.append((rid, ref["id"], "none", req["hash"]))
                if k == "deviates":
                    declared.append((rid, ref["id"], ref["decision"]))
                    if ref["decision"] not in ctx.decisions:
                        missing.append((rid, ref["decision"]))
                elif ref["id"] in devs:
                    conflicts.append((rid, ref["id"], devs[ref["id"]], bool(cited_p & set(devs[ref["id"]]))))
            elif k == "decision":
                d = ctx.decisions.get(ref["id"])
                if not d:
                    missing.append((rid, ref["id"]))
                elif d["struck"]:
                    struck.append((rid, ref["id"]))
            elif k == "official" and not ref["dated"]:
                undated.append((rid, ref["text"]))
            elif k == "unknown":
                unknown.append((rid, ref["text"]))
    return {"no_source": no_source, "unshaped": unshaped, "uncovered": uncovered, "stale": stale, "missing": missing,
            "struck": struck, "declared": declared, "conflicts": conflicts, "unknown": unknown, "undated": undated,
            "with_source": [r for r in ctx.r1 if ctx.sources.get(r)]}


def cmd_gaps(ctx):
    g = gaps(ctx)
    snap = ctx.snap
    n_unc = sum(len(v) for v in g["uncovered"].values())
    print(f"# Requirement gaps ({snap.name}; BACKLOG.md, MVP-CHECKLIST.md, trace/sources-seed.tsv)")
    print(f"Release 1 rows: {len(ctx.r1)} · with a Source: {len(g['with_source'])} · shaped with no Source: "
          f"{len(g['no_source'])} · checklist rows not shaped (unmapped): {len(g['unshaped'])} · team ids in force: "
          f"{sum(1 for r in snap.reqs.values() if not r['withdrawn'])}, no row covers {n_unc} · to the founder: {len(g['conflicts']) + len(g['declared']) + len(g['struck'])}"
          f" · Source problems: {len(g['stale']) + len(g['missing']) + len(g['unknown']) + len(g['undated'])}\n")
    print(f"## 1. Release 1 rows shaped with no Source ({len(g['no_source'])})")
    print(", ".join(g["no_source"]) or "none")
    print(f"\n## 2. Checklist rows not shaped: unmapped ({len(g['unshaped'])})")
    for c in g["unshaped"]:
        print(f"map {c['map']}: {re.sub(r'[*`]', '', c['cap'])} · rows: {', '.join(c['row_ids']) or 'none'}")
    live = sum(1 for r in snap.reqs.values() if not r["withdrawn"])
    print(f"\n## 3. Team requirement ids no row covers, by module ({n_unc} of {live}; withdrawn ids left out)")
    for m, ids in sorted(g["uncovered"].items(), key=lambda kv: id_key(kv[0])):
        total = len([r for r in snap.by_module()[m] if not snap.reqs[r]["withdrawn"]])
        print(f"{m}: {len(ids)} of {total} not covered{': ' + ', '.join(ids) if ids else ''}")
    print(f"\n## 4. To the founder: Source against a P-decision (AGENTS rule 2)")
    for rid, tid, ps, ack in g["conflicts"]:
        print(f"{rid} follows {tid}, but {', '.join(ps)} deviates from it{' (row cites the decision: say deviates)' if ack else ''}")
    for rid, tid, p in g["declared"]:
        print(f"{rid} deviates from {tid} by {p} (declared; founder to confirm)")
    for rid, p in g["struck"]:
        print(f"{rid} cites {p}, which is struck through (superseded)")
    if not (g["conflicts"] or g["declared"] or g["struck"]):
        print("none")
    print(f"\n## 5. Source problems (row owner fixes)")
    for rid, tid, was, now in g["stale"]:
        print(f"{rid}: {tid} hash {was} -> now {now}{' (text changed since mapped)' if was != 'none' else ' (no hash)'}")
    for rid, x in g["missing"]:
        print(f"{rid}: {x} not found")
    for rid, t in g["undated"]:
        print(f"{rid}: official source without a date: {t}")
    for rid, t in g["unknown"]:
        print(f"{rid}: unread Source item: {t}")
    if not (g["stale"] or g["missing"] or g["undated"] or g["unknown"]):
        print("none")
    return 0


def render_block(ctx):
    ctx.load()
    caps = ctx.read(ctx.caps_path)
    snap = ctx.snap
    with_src = [r for r in ctx.r1 if ctx.sources.get(r)]
    out = [BEGIN, "", "### Requirement trace (generated, TR-1, P-595)", "",
           f"Requirement snapshot `{snap.name}`. Release 1 rows with a `Source:`: {len(with_src)} of {len(ctx.r1)}. "
           "Source = the team's requirement ids (with `#hash` in the row), P-decisions, official sources; "
           "\"changed\" = the text moved since the row was mapped. qa capability = `qa/CAPABILITIES.md` rows that cite "
           "the map row's BACKLOG rows. Regenerate with `python3 product/tools/trace-requirements.py --render`.", "",
           "| Map row | Capability | Source | Row status | Rows | qa capability |", "|---|---|---|---|---|---|"]
    for c in ctx.checklist:
        ids, seen = [], set()
        for rid in c["row_ids"]:
            for ref in ctx.sources.get(rid, []):
                if ref["kind"] == "team":
                    req = snap.reqs.get(ref["id"])
                    tag = ref["id"] + ("" if req and ref.get("hash") == req["hash"] else (" (not found)" if not req else " (changed)"))
                elif ref["kind"] == "deviates":
                    tag = f"not {ref['id']} ({ref['decision']})"
                elif ref["kind"] == "decision":
                    tag = ref["id"]
                elif ref["kind"] == "official":
                    tag = "official"
                else:
                    continue
                if tag not in seen:
                    seen.add(tag); ids.append(tag)
        cap_ids = capabilities_for(caps, c["row_ids"]) if c["row_ids"] else []
        src = ", ".join(ids) if ids else ("no Source yet" if c["row_ids"] else "no row")
        out.append(f"| {c['map']} | {c['cap']} | {src} | {status_word(c['status'])} | "
                   f"{', '.join(c['row_ids']) or 'none'} | {', '.join(cap_ids) or 'none yet'} |")
    out += ["", END]
    return "\n".join(out)


def place_block(text, block):
    if BEGIN in text and END in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        return text[:a] + block + text[b:]
    lines = text.split("\n")
    inA, at = False, None
    for i, line in enumerate(lines):
        if line.startswith("## "):
            if inA:
                at = i
                break
            inA = line.startswith("## A.")
        elif inA and line.startswith("### Flags"):
            at = i
            break
    if at is None:
        raise SystemExit("MVP-CHECKLIST.md has no section '## A.' to render into")
    while at > 0 and lines[at - 1].strip() in ("", "---"):
        at -= 1
    return "\n".join(lines[:at] + ["", block] + lines[at:])


def cmd_render(ctx, check):
    text = ctx.read(ctx.checklist_path)
    new = place_block(text, render_block(ctx))
    if new == text:
        print("MVP-CHECKLIST.md trace block: up to date"); return 0
    if check:
        print("MVP-CHECKLIST.md trace block is out of date: run trace-requirements.py --render", file=sys.stderr); return 1
    with open(ctx.checklist_path, "w", encoding="utf-8") as fh:
        fh.write(new)
    print("MVP-CHECKLIST.md trace block written"); return 0


def cmd_ci(ctx, base):
    """A shaped Release 1 row added (or newly shaped) since base must have a Source. Records-only (P-547 (4))."""
    ctx.load()
    if os.path.isfile(base):
        old_text = ctx.read(base)
    else:
        rel = os.path.relpath(os.path.abspath(ctx.backlog_path), subprocess.check_output(
            ["git", "-C", os.path.dirname(os.path.abspath(ctx.backlog_path)), "rev-parse", "--show-toplevel"], text=True).strip())
        try:
            old_text = subprocess.check_output(["git", "-C", PRODUCT, "show", f"{base}:{rel}"], text=True, stderr=subprocess.DEVNULL)
        except subprocess.CalledProcessError:
            old_text = ""
    old = parse_backlog(old_text)
    new_shaped = [r for r in ctx.r1 if ctx.rows.get(r, {}).get("shaped") and not old.get(r, {}).get("shaped")]
    bad = [r for r in new_shaped if not ctx.sources.get(r)]
    print(f"trace check: {len(new_shaped)} Release 1 row(s) shaped since {base}: {', '.join(new_shaped) or 'none'}")
    if bad:
        for r in bad:
            print(f"::error::BACKLOG row {r} is a shaped Release 1 row with no `Source:` (P-595; TR-1). Add "
                  f"`Source: <team ids with #hash, P-ids or official source>` to its row "
                  f"(hashes: trace-requirements.py --hash <id>).")
        return 1
    print("trace check: every new shaped Release 1 row has a Source")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__ or "requirement traceability (TR-1, P-595)")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--brief", metavar="ROW")
    g.add_argument("--refresh", nargs=2, metavar=("OLD", "NEW"))
    g.add_argument("--gaps", action="store_true")
    g.add_argument("--render", action="store_true")
    g.add_argument("--ci", metavar="BASE")
    g.add_argument("--hash", nargs="+", metavar="ID")
    ap.add_argument("--check", action="store_true", help="with --render: exit 1 if the block would change")
    ap.add_argument("--snapshot", help="requirements folder or date (default: the newest ../domain/requirements-*)")
    ap.add_argument("--backlog"); ap.add_argument("--checklist"); ap.add_argument("--decisions")
    ap.add_argument("--capabilities"); ap.add_argument("--seed")
    a = ap.parse_args(argv)
    ctx = Ctx(a)
    if a.brief:
        return cmd_brief(ctx, a.brief)
    if a.refresh:
        return cmd_refresh(ctx, *a.refresh)
    if a.gaps:
        return cmd_gaps(ctx)
    if a.render:
        return cmd_render(ctx, a.check)
    if a.ci:
        return cmd_ci(ctx, a.ci)
    return cmd_hash(ctx, a.hash)


