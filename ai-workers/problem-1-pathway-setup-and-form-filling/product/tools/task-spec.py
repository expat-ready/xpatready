#!/usr/bin/env python3
"""task-spec.py: one generated spec per task (lab register LR-106; software-factory deep audit, "What the builder reads":
"One generated task spec per task: requirement text, decisions in words, Done-when check"; Claude Code best practices:
"Give Claude something it can run that comes back pass or fail.").

A builder reads this one file instead of the row, the source slice and decisions by number. It adds nothing new: the
row's own cells from BACKLOG.md (its Done when first), then the exact requirement and decision text that
`trace-requirements.py --brief` prints (P-604). The feature list "with a passes field" is qa/CAPABILITIES.md's verdict
column (Works / Partial / Not built), so no second list is kept. Standard library only, US$0, no network.

  python3 -I product/tools/task-spec.py ROW [--out FILE] [--backlog F --decisions F --trace F --requirements DIR]
Exit 0 written; 1 the row has no Done when or no Source (shape it first); 2 no such row. Test: test_task_spec.py.
"""
import argparse, pathlib, re, subprocess, sys

HERE = pathlib.Path(__file__).resolve().parent
PRODUCT = HERE.parent


def cells(line):
    return [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]


def find_row(text, row_id):
    """(header cells, row cells) of the first table row whose first cell's id is row_id."""
    lines = text.split("\n")
    header = None
    for n, l in enumerate(lines):
        if not l.startswith("|"):
            header = None
            continue
        if re.match(r"^\|\s*:?-{3,}", l):
            header = cells(lines[n - 1]) if n else None
            continue
        c = cells(l)
        if header and c and re.sub(r"[*~]", "", c[0]).strip().split(" ")[0] == row_id:
            return header, c
    return None, None


def words(cell):
    return re.sub(r"<br\s*/?>", "\n", cell).strip()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("row")
    ap.add_argument("--out")
    ap.add_argument("--backlog", default=str(PRODUCT / "BACKLOG.md"))
    ap.add_argument("--decisions", default=str(PRODUCT / "DECISIONS.md"))
    ap.add_argument("--trace", default=str(PRODUCT / "compliance-trace.md"))
    ap.add_argument("--requirements")
    a = ap.parse_args(argv)
    header, row = find_row(pathlib.Path(a.backlog).read_text(encoding="utf-8"), a.row)
    if not row:
        print(f"task-spec: no row {a.row} in {a.backlog}", file=sys.stderr)
        return 2
    named = {h.lower(): (h, words(row[k])) for k, h in enumerate(header) if k < len(row) and h}
    done = next((v for k, (h, v) in named.items() if "done when" in k), "")
    if not done or done.lower() in {"", "-", "—", "tbd", "todo"}:
        print(f"task-spec: {a.row} has no Done when; shape the row first", file=sys.stderr)
        return 1
    cmd = [sys.executable, "-I", str(HERE / "trace-requirements.py"), "--brief", a.row, "--backlog", a.backlog,
           "--decisions", a.decisions, "--trace", a.trace] + (["--requirements", a.requirements] if a.requirements else [])
    brief = subprocess.run(cmd, capture_output=True, text=True)
    if brief.returncode != 0:
        print(f"task-spec: {brief.stderr.strip() or 'trace-requirements --brief failed'}", file=sys.stderr)
        return 1
    out = [f"# Task spec: {a.row}", "",
           "Generated by product/tools/task-spec.py from BACKLOG.md and trace-requirements.py --brief. Read only this file;",
           "the task ends when the Done-when check below passes.", "",
           "## Done when", "", done, ""]
    for k, (h, v) in named.items():
        if "done when" not in k and k != "#" and v:
            out += [f"## {h}", "", v, ""]
    out += [brief.stdout.replace(f"# {a.row}: requirement text", "## Requirement text and decisions", 1)]
    # Decisions the row names outside its Source line, in words too (the brief prints only Source items).
    named_ids = sorted(set(re.findall(r"\bP-\d+\b", " ".join(row))) - set(re.findall(r"## (P-\d+) ", brief.stdout)),
                       key=lambda i: int(i[2:]))
    dec = {}
    for l in pathlib.Path(a.decisions).read_text(encoding="utf-8").split("\n"):
        m = re.match(r"^\|\s*(?:~~)?(P-\d+)(?:~~)?\s*\|", l)
        if m and m.group(1) in named_ids:
            dec.setdefault(m.group(1), l.strip())
    for i in named_ids:
        out += [f"## {i} (DECISIONS.md, named in the row)", "", dec.get(i, f"> WARNING: {i} is not a DECISIONS.md row"), ""]
    text = "\n".join(out).rstrip() + "\n"
    if a.out:
        pathlib.Path(a.out).write_text(text, encoding="utf-8")
        print(f"task-spec: {a.row} -> {a.out} ({len(text.encode())} bytes)")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
